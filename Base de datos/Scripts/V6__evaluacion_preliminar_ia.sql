CREATE TABLE IF NOT EXISTS public.ai_preliminary_evaluations (
  id_evaluacion_ia integer GENERATED BY DEFAULT AS IDENTITY,
  id_propuesta integer NOT NULL,
  modelo_ia character varying(80) NOT NULL DEFAULT 'gemini-3.5-flash',
  modo_generacion character varying(40) NOT NULL DEFAULT 'gemini_online',
  puntaje_preliminar numeric(5,2) NOT NULL DEFAULT 0,
  recomendacion_global character varying(60) NOT NULL,
  tiene_bloqueo_obligatorio boolean NOT NULL DEFAULT false,
  resumen_ejecutivo text NOT NULL,
  referencia_vinculacion jsonb NOT NULL DEFAULT '{}'::jsonb,
  referencia_comite_tecnico jsonb NOT NULL DEFAULT '{}'::jsonb,
  referencia_consejo_escuela jsonb NOT NULL DEFAULT '{}'::jsonb,
  referencia_direccion_vie jsonb NOT NULL DEFAULT '{}'::jsonb,
  referencia_cie jsonb NOT NULL DEFAULT '{}'::jsonb,
  fortalezas jsonb NOT NULL DEFAULT '[]'::jsonb,
  alertas_normativas jsonb NOT NULL DEFAULT '[]'::jsonb,
  criterios_sugeridos jsonb NOT NULL DEFAULT '{}'::jsonb,
  fecha_generacion timestamp without time zone NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT ai_preliminary_evaluations_pkey PRIMARY KEY (id_evaluacion_ia),
  CONSTRAINT uq_ai_eval_propuesta UNIQUE (id_propuesta),
  CONSTRAINT fk_ai_eval_propuesta FOREIGN KEY (id_propuesta)
    REFERENCES public.propuestas(id_propuesta) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ai_eval_propuesta
  ON public.ai_preliminary_evaluations (id_propuesta, fecha_generacion DESC);

-- Políticas RLS para acceso desde el pool de conexiones y cliente Supabase
ALTER TABLE public.ai_preliminary_evaluations ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'ai_preliminary_evaluations'
      AND policyname = 'Permitir lectura de evaluaciones IA'
  ) THEN
    CREATE POLICY "Permitir lectura de evaluaciones IA"
      ON public.ai_preliminary_evaluations FOR SELECT USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'ai_preliminary_evaluations'
      AND policyname = 'Permitir insercion de evaluaciones IA'
  ) THEN
    CREATE POLICY "Permitir insercion de evaluaciones IA"
      ON public.ai_preliminary_evaluations FOR INSERT WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE tablename = 'ai_preliminary_evaluations'
      AND policyname = 'Permitir actualizacion de evaluaciones IA'
  ) THEN
    CREATE POLICY "Permitir actualizacion de evaluaciones IA"
      ON public.ai_preliminary_evaluations FOR UPDATE USING (true);
  END IF;
END $$;
